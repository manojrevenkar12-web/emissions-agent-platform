import { AnimatePresence, motion, useReducedMotion } from "framer-motion";
import { useEffect, useState } from "react";
import { EvalGate } from "../features/evals/EvalGate";
import { Governance } from "../features/governance/Governance";
import { Manifest } from "../features/manifest/Manifest";
import { Monitor } from "../features/monitor/Monitor";
import { Results } from "../features/results/Results";
import { Safeguards } from "../features/safeguards/Safeguards";
import { Trace } from "../features/trace/Trace";
import { type Split, useReport } from "../shared/data/report";
import { EmptyState, ErrorState, Skeleton } from "../shared/ui/States";
import styles from "./App.module.css";

type Theme = "light" | "dark";

function initialTheme(): Theme {
  try {
    const saved = localStorage.getItem("eap-theme");
    if (saved === "light" || saved === "dark") return saved;
  } catch {
    /* storage can be unavailable */
  }
  return window.matchMedia?.("(prefers-color-scheme: dark)").matches ? "dark" : "light";
}

function Body({ split }: { split: Split }) {
  if (!split.samples?.file) return <EmptyState title="This report has no sample run">Run python -m eap.cli run dev to produce one.</EmptyState>;
  return (
    <>
      <Manifest file={split.samples.file} />
      <Results split={split} />
      <Safeguards split={split} />
      <Trace samples={split.samples} />
      <Monitor samples={split.samples} detect={split.designs.platform?.monitor_detect_days as (number | null)[] | undefined} />
      <EvalGate split={split} />
      <Governance split={split} />
    </>
  );
}

export function App() {
  const { load, retry } = useReport();
  const [which, setWhich] = useState<"dev" | "heldout">("dev");
  const [theme, setTheme] = useState<Theme>(initialTheme);
  const reduce = useReducedMotion();
  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    try {
      localStorage.setItem("eap-theme", theme);
    } catch {
      /* ignore */
    }
  }, [theme]);
  const report = load.state === "ready" ? load.report : null;
  const split = report ? (which === "heldout" && report.heldout ? report.heldout : report.dev) : null;
  return (
    <div className={styles.page}>
      <header className={styles.bar}>
        <a className={styles.brand} href="https://github.com/manojrevenkar12-web/emissions-agent-platform">
          emissions-agent-platform
        </a>
        <nav className={styles.controls} aria-label="Report controls">
          {report?.heldout && (
            <div className={styles.switch} role="tablist" aria-label="Which seeds">
              {(["dev", "heldout"] as const).map((k) => (
                <button key={k} type="button" role="tab" aria-selected={which === k} className={styles.switchBtn} onClick={() => setWhich(k)}>
                  {which === k && <motion.span layoutId="split-pill" className={styles.switchPill} transition={{ duration: reduce ? 0 : 0.25 }} />}
                  <span className={styles.switchText}>{k === "dev" ? "Development seeds" : "Held-out, run once"}</span>
                </button>
              ))}
            </div>
          )}
          <button type="button" className={styles.theme} onClick={() => setTheme(theme === "dark" ? "light" : "dark")} aria-label={`Switch to ${theme === "dark" ? "light" : "dark"} theme`}>
            {theme === "dark" ? "Light" : "Dark"}
          </button>
        </nav>
      </header>
      <main className={styles.main}>
        {load.state === "loading" && <Skeleton lines={6} label="Loading the report" />}
        {load.state === "error" && <ErrorState message={load.message} onRetry={retry} />}
        <AnimatePresence mode="wait">
          {split && (
            <motion.div key={split.split} className={styles.stack} initial={reduce ? false : { opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} transition={{ duration: 0.2 }}>
              <Body split={split} />
            </motion.div>
          )}
        </AnimatePresence>
      </main>
      <footer className={styles.footer}>
        <p>
          Everything here is simulated: shippers, carriers, files, replies and questions come from a world with its own hidden truth, and the numbers are what each
          design got right or wrong against it. Generated by <code>python -m eap.cli report</code>.
        </p>
      </footer>
    </div>
  );
}
